const express = require('express');
const PDFDocument = require('pdfkit');
const { verifyToken } = require('../middleware/auth');
const googleDriveService = require('../services/googleDrive');
const moment = require('moment');

const router = express.Router();

/**
 * @route   GET /api/export/pdf/:driverId
 * @desc    Export driver test report as PDF
 * @access  Private
 */
router.get('/pdf/:driverId', verifyToken, async (req, res) => {
  try {
    const { driverId } = req.params;
    
    // Get driver data
    const results = await googleDriveService.searchDriverData(driverId);
    
    if (results.length === 0) {
      return res.status(404).json({
        error: {
          message: 'Driver record not found'
        }
      });
    }

    const driverData = results.find(d => d.driverId === driverId) || results[0];

    // Create PDF document
    const doc = new PDFDocument({ margin: 50 });
    
    // Set response headers
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${driverId}_test_report.pdf"`);
    
    // Pipe PDF to response
    doc.pipe(res);

    // Company Header
    doc.fontSize(20).text('LED Driver Test Report', { align: 'center' });
    doc.fontSize(12).text('Electronics Manufacturing Company', { align: 'center' });
    doc.moveDown();

    // Report Info
    doc.fontSize(14).text('Report Information', { underline: true });
    doc.fontSize(10);
    doc.text(`Generated: ${moment().format('YYYY-MM-DD HH:mm:ss')}`);
    doc.text(`Generated by: ${req.user.name || req.user.email}`);
    doc.text(`Driver ID: ${driverData.driverId || 'N/A'}`);
    doc.text(`Driver Name: ${driverData.driverName || 'N/A'}`);
    doc.text(`Serial Number: ${driverData.serialNumber || 'N/A'}`);
    doc.text(`Test Date: ${moment(driverData.testDate).format('YYYY-MM-DD') || 'N/A'}`);
    doc.text(`Tested By: ${driverData.testedBy || 'N/A'}`);
    doc.moveDown();

    // Input Specifications
    doc.fontSize(14).text('Input Specifications', { underline: true });
    doc.fontSize(10);
    doc.text(`Input Voltage: ${driverData.inputVoltage || 'N/A'} V`);
    doc.text(`Input Current: ${driverData.inputCurrent || 'N/A'} A`);
    doc.text(`Input Wattage: ${driverData.inputWattage || 'N/A'} W`);
    doc.text(`Power Factor: ${driverData.powerFactor || 'N/A'}`);
    doc.moveDown();

    // Output Specifications
    doc.fontSize(14).text('Output Specifications', { underline: true });
    doc.fontSize(10);
    doc.text(`Output Voltage: ${driverData.outputVoltage || 'N/A'} V`);
    doc.text(`Output Current: ${driverData.outputCurrent || 'N/A'} A`);
    doc.text(`Output Wattage: ${driverData.outputWattage || 'N/A'} W`);
    doc.text(`Efficiency: ${driverData.efficiency || 'N/A'} %`);
    doc.moveDown();

    // Quality Metrics
    doc.fontSize(14).text('Quality Metrics', { underline: true });
    doc.fontSize(10);
    doc.text(`THD (Total Harmonic Distortion): ${driverData.thd || 'N/A'} %`);
    doc.text(`Ripple Current: ${driverData.rippleCurrent || 'N/A'} mA`);
    doc.text(`Ripple Voltage: ${driverData.rippleVoltage || 'N/A'} mV`);
    doc.moveDown();

    // Safety Tests
    doc.fontSize(14).text('Safety Tests', { underline: true });
    doc.fontSize(10);
    
    const surgeResult = driverData.surgeProtectionResult || 'N/A';
    const surgeColor = surgeResult === 'Pass' ? 'green' : surgeResult === 'Fail' ? 'red' : 'black';
    doc.fillColor(surgeColor).text(`Surge Protection: ${surgeResult}`);
    if (driverData.surgeProtectionKvLevel) {
      doc.fillColor('black').text(`  kV Level: ${driverData.surgeProtectionKvLevel} kV`);
    }

    const hvResult = driverData.highVoltageTestResult || 'N/A';
    const hvColor = hvResult === 'Pass' ? 'green' : hvResult === 'Fail' ? 'red' : 'black';
    doc.fillColor(hvColor).text(`High Voltage Test: ${hvResult}`);
    if (driverData.highVoltageTestConditions) {
      doc.fillColor('black').text(`  Conditions: ${driverData.highVoltageTestConditions}`);
    }

    const thermalResult = driverData.thermalTestResult || 'N/A';
    const thermalColor = thermalResult === 'Pass' ? 'green' : thermalResult === 'Fail' ? 'red' : 'black';
    doc.fillColor(thermalColor).text(`Thermal Test: ${thermalResult}`);
    if (driverData.thermalTestRemarks) {
      doc.fillColor('black').text(`  Remarks: ${driverData.thermalTestRemarks}`);
    }
    
    doc.fillColor('black'); // Reset color
    doc.moveDown();

    // Additional Information
    if (driverData.componentDetails || driverData.issues || driverData.remarks) {
      doc.fontSize(14).text('Additional Information', { underline: true });
      doc.fontSize(10);
      
      if (driverData.componentDetails) {
        doc.text(`Component Details: ${driverData.componentDetails}`);
      }
      
      if (driverData.issues) {
        doc.text(`Issues/Abnormalities: ${driverData.issues}`);
      }
      
      if (driverData.remarks) {
        doc.text(`Remarks: ${driverData.remarks}`);
      }
      
      doc.moveDown();
    }

    // Overall Result
    doc.fontSize(14).text('Overall Test Result', { underline: true });
    doc.fontSize(12);
    
    const allTestsPassed = surgeResult === 'Pass' && hvResult === 'Pass' && thermalResult === 'Pass';
    const overallResult = allTestsPassed ? 'PASS' : 'FAIL';
    const overallColor = allTestsPassed ? 'green' : 'red';
    
    doc.fillColor(overallColor).text(`Status: ${overallResult}`, { align: 'center' });
    doc.fillColor('black');

    // Footer
    doc.fontSize(8);
    doc.text(`This report was generated automatically on ${moment().format('YYYY-MM-DD HH:mm:ss')}`, 50, doc.page.height - 50, { align: 'center' });

    // Finalize PDF
    doc.end();

  } catch (error) {
    console.error('PDF export error:', error);
    res.status(500).json({
      error: {
        message: 'Failed to generate PDF report',
        details: error.message
      }
    });
  }
});

/**
 * @route   GET /api/export/csv
 * @desc    Export all driver data as CSV
 * @access  Private
 */
router.get('/csv', verifyToken, async (req, res) => {
  try {
    const { startDate, endDate, limit = 1000 } = req.query;
    
    // Get all driver data
    const allData = await googleDriveService.getAllDriverData(parseInt(limit), 0);
    let drivers = allData.data;

    // Filter by date range if provided
    if (startDate || endDate) {
      drivers = drivers.filter(driver => {
        const testDate = moment(driver.testDate);
        if (startDate && testDate.isBefore(moment(startDate))) return false;
        if (endDate && testDate.isAfter(moment(endDate))) return false;
        return true;
      });
    }

    if (drivers.length === 0) {
      return res.status(404).json({
        error: {
          message: 'No data found for the specified criteria'
        }
      });
    }

    // CSV Headers
    const headers = [
      'Driver ID',
      'Driver Name',
      'Serial Number',
      'Test Date',
      'Tested By',
      'Input Voltage (V)',
      'Input Current (A)',
      'Input Wattage (W)',
      'Power Factor',
      'Output Voltage (V)',
      'Output Current (A)',
      'Output Wattage (W)',
      'Efficiency (%)',
      'THD (%)',
      'Ripple Current (mA)',
      'Ripple Voltage (mV)',
      'Surge Protection',
      'Surge kV Level',
      'High Voltage Test',
      'HV Test Conditions',
      'Thermal Test',
      'Thermal Remarks',
      'Component Details',
      'Issues',
      'Remarks',
      'Overall Result'
    ];

    // Generate CSV content
    let csvContent = headers.join(',') + '\n';

    drivers.forEach(driver => {
      const overallResult = (
        driver.surgeProtectionResult === 'Pass' &&
        driver.highVoltageTestResult === 'Pass' &&
        driver.thermalTestResult === 'Pass'
      ) ? 'PASS' : 'FAIL';

      const row = [
        driver.driverId || '',
        driver.driverName || '',
        driver.serialNumber || '',
        moment(driver.testDate).format('YYYY-MM-DD') || '',
        driver.testedBy || '',
        driver.inputVoltage || '',
        driver.inputCurrent || '',
        driver.inputWattage || '',
        driver.powerFactor || '',
        driver.outputVoltage || '',
        driver.outputCurrent || '',
        driver.outputWattage || '',
        driver.efficiency || '',
        driver.thd || '',
        driver.rippleCurrent || '',
        driver.rippleVoltage || '',
        driver.surgeProtectionResult || '',
        driver.surgeProtectionKvLevel || '',
        driver.highVoltageTestResult || '',
        driver.highVoltageTestConditions || '',
        driver.thermalTestResult || '',
        driver.thermalTestRemarks || '',
        driver.componentDetails || '',
        driver.issues || '',
        driver.remarks || '',
        overallResult
      ].map(field => `"${String(field).replace(/"/g, '""')}"`); // Escape quotes

      csvContent += row.join(',') + '\n';
    });

    // Set response headers
    const filename = `led_driver_test_data_${moment().format('YYYY-MM-DD')}.csv`;
    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    res.send(csvContent);

  } catch (error) {
    console.error('CSV export error:', error);
    res.status(500).json({
      error: {
        message: 'Failed to generate CSV export',
        details: error.message
      }
    });
  }
});

/**
 * @route   GET /api/export/summary-report
 * @desc    Export summary report with statistics
 * @access  Private
 */
router.get('/summary-report', verifyToken, async (req, res) => {
  try {
    const { format = 'pdf' } = req.query;
    
    // Get all data for analysis
    const allData = await googleDriveService.getAllDriverData(1000, 0);
    const drivers = allData.data;

    if (drivers.length === 0) {
      return res.status(404).json({
        error: {
          message: 'No data available for summary report'
        }
      });
    }

    // Calculate statistics
    const totalTests = drivers.length;
    const passedTests = drivers.filter(d => 
      d.surgeProtectionResult === 'Pass' &&
      d.highVoltageTestResult === 'Pass' &&
      d.thermalTestResult === 'Pass'
    ).length;
    
    const passRate = (passedTests / totalTests) * 100;
    
    const efficiencyValues = drivers
      .map(d => parseFloat(d.efficiency))
      .filter(e => !isNaN(e) && e > 0);
    
    const avgEfficiency = efficiencyValues.length > 0 
      ? efficiencyValues.reduce((sum, eff) => sum + eff, 0) / efficiencyValues.length 
      : 0;

    const recentTests = drivers.filter(d => 
      moment(d.testDate).isAfter(moment().subtract(30, 'days'))
    ).length;

    if (format === 'pdf') {
      // Generate PDF summary report
      const doc = new PDFDocument({ margin: 50 });
      
      res.setHeader('Content-Type', 'application/pdf');
      res.setHeader('Content-Disposition', `attachment; filename="led_driver_summary_${moment().format('YYYY-MM-DD')}.pdf"`);
      
      doc.pipe(res);

      // Header
      doc.fontSize(20).text('LED Driver Testing Summary Report', { align: 'center' });
      doc.fontSize(12).text('Electronics Manufacturing Company', { align: 'center' });
      doc.moveDown(2);

      // Report Period
      doc.fontSize(14).text('Report Information', { underline: true });
      doc.fontSize(10);
      doc.text(`Generated: ${moment().format('YYYY-MM-DD HH:mm:ss')}`);
      doc.text(`Generated by: ${req.user.name || req.user.email}`);
      doc.text(`Total Records: ${totalTests}`);
      doc.moveDown();

      // Key Statistics
      doc.fontSize(14).text('Key Statistics', { underline: true });
      doc.fontSize(12);
      doc.text(`Total Tests Conducted: ${totalTests}`);
      doc.text(`Tests Passed: ${passedTests}`);
      doc.text(`Tests Failed: ${totalTests - passedTests}`);
      doc.text(`Overall Pass Rate: ${passRate.toFixed(2)}%`);
      doc.text(`Average Efficiency: ${avgEfficiency.toFixed(2)}%`);
      doc.text(`Tests in Last 30 Days: ${recentTests}`);
      doc.moveDown();

      // Test Breakdown
      doc.fontSize(14).text('Test Breakdown', { underline: true });
      doc.fontSize(10);
      
      const surgePassCount = drivers.filter(d => d.surgeProtectionResult === 'Pass').length;
      const hvPassCount = drivers.filter(d => d.highVoltageTestResult === 'Pass').length;
      const thermalPassCount = drivers.filter(d => d.thermalTestResult === 'Pass').length;
      
      doc.text(`Surge Protection Tests Passed: ${surgePassCount}/${totalTests} (${((surgePassCount/totalTests)*100).toFixed(1)}%)`);
      doc.text(`High Voltage Tests Passed: ${hvPassCount}/${totalTests} (${((hvPassCount/totalTests)*100).toFixed(1)}%)`);
      doc.text(`Thermal Tests Passed: ${thermalPassCount}/${totalTests} (${((thermalPassCount/totalTests)*100).toFixed(1)}%)`);

      doc.end();
    } else {
      // Return JSON summary
      res.json({
        reportDate: moment().format('YYYY-MM-DD HH:mm:ss'),
        generatedBy: req.user.name || req.user.email,
        summary: {
          totalTests,
          passedTests,
          failedTests: totalTests - passedTests,
          passRate: Math.round(passRate * 100) / 100,
          averageEfficiency: Math.round(avgEfficiency * 100) / 100,
          recentTests
        },
        testBreakdown: {
          surgeProtection: {
            passed: drivers.filter(d => d.surgeProtectionResult === 'Pass').length,
            failed: drivers.filter(d => d.surgeProtectionResult === 'Fail').length
          },
          highVoltage: {
            passed: drivers.filter(d => d.highVoltageTestResult === 'Pass').length,
            failed: drivers.filter(d => d.highVoltageTestResult === 'Fail').length
          },
          thermal: {
            passed: drivers.filter(d => d.thermalTestResult === 'Pass').length,
            failed: drivers.filter(d => d.thermalTestResult === 'Fail').length
          }
        }
      });
    }

  } catch (error) {
    console.error('Summary report error:', error);
    res.status(500).json({
      error: {
        message: 'Failed to generate summary report',
        details: error.message
      }
    });
  }
});

module.exports = router;